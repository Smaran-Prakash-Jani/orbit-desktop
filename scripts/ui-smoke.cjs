const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser=await chromium.launch({headless:true,...(process.env.ORBIT_BROWSER_PATH?{executablePath:process.env.ORBIT_BROWSER_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto(pathToFileURL(path.resolve(__dirname,'../ui/index.html')).href);
    await page.locator('#cpu-value').filter({hasText:'18.4'}).waitFor();
    await fs.mkdir(path.resolve(__dirname,'../test-results'),{recursive:true});
    await page.screenshot({path:'test-results/overview-glass.png',fullPage:true,animations:'disabled'});
    assert.equal(await page.locator('html').getAttribute('data-theme'),null);
    assert.equal(await page.locator('[data-theme-choice]').count(),0);
    assert.equal(await page.locator('body').evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)');
    assert.equal(await page.locator('.landscape-banner').count(),0);
    assert.equal(await page.locator('[data-gauge]').count(),3);
    assert.ok(parseFloat(await page.locator('[data-gauge="cpu"]').evaluate(el=>el.style.getPropertyValue('--gauge-angle'))) > 0);
    assert.ok((await page.getByRole('button',{name:'Close window'}).boundingBox()).width>=24);
    await page.getByRole('button',{name:'Processes',exact:true}).click();
    await page.locator('#process-rows tr').first().waitFor();
    await page.getByLabel('Filter processes').fill('firefox');
    assert.equal(await page.locator('#process-rows tr').count(),1);
    assert.match(await page.locator('#process-rows').innerText(),/Firefox/);
    await page.getByLabel('Filter processes').fill('no-match-1234');
    assert.match(await page.locator('#process-rows').innerText(),/No processes match/);
    await page.getByRole('button',{name:'Storage',exact:true}).click();
    await page.getByRole('button',{name:'Inspect a folder',exact:true}).click();
    await page.getByText('Projects',{exact:true}).waitFor();
    assert.equal(await page.locator('.folder-row').count(),5);
    await page.getByRole('button',{name:'Health check',exact:true}).click();
    await page.locator('#view-health').getByRole('button',{name:'Run health check',exact:true}).click();
    await page.locator('.check-card').first().waitFor();
    assert.equal(await page.locator('.check-card').count(),6);
    await page.locator('.check-card summary').first().click();
    await page.screenshot({path:'test-results/health.png',fullPage:true});
    await page.keyboard.press('Control+k');
    await page.getByLabel('Search commands').fill('network');
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#view-network').isVisible(),true);
    assert.match(await page.locator('#network-download').innerText(),/428/);
    await page.getByRole('button',{name:'Settings',exact:true}).click();
    await page.getByLabel('Reduce motion').check();
    const transparency=page.locator('#view-settings [data-transparency-slider]');
    await transparency.focus();await transparency.press('End');
    assert.equal(await transparency.inputValue(),'80');
    assert.equal(await page.locator('html').evaluate(el=>el.style.getPropertyValue('--window-alpha')),'0.2');
    await page.reload();
    assert.match(await page.locator('body').getAttribute('class'),/quiet-motion/);
    await page.getByRole('button',{name:'Settings',exact:true}).click();
    assert.equal(await transparency.inputValue(),'80');
    await page.getByRole('button',{name:'Adjust transparency'}).click();
    assert.equal(await page.locator('#transparency-popover [data-transparency-slider]').inputValue(),'80');
    await page.screenshot({path:'test-results/transparency-popover.png',animations:'disabled'});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#transparency-popover').isVisible(),false);
    await transparency.evaluate(el=>{el.value='48';el.dispatchEvent(new Event('input',{bubbles:true}));});
    await page.getByRole('button',{name:'Overview',exact:true}).click();
    await page.screenshot({path:'test-results/overview-after-preferences.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'no horizontal overflow on mobile');
    await page.screenshot({path:'test-results/overview-mobile.png',fullPage:true});
    await page.setViewportSize({width:1366,height:768});
    await page.screenshot({path:'test-results/overview-laptop.png',fullPage:true});
    const lowerCards=await page.locator('.overview-bottom').boundingBox();
    const windowPane=await page.locator('main').boundingBox();
    assert.ok(lowerCards.y+lowerCards.height<=windowPane.y+windowPane.height+1,'laptop overview cards fit in the window');
    await page.locator('main').evaluate(el=>{el.scrollTop=250;});
    await page.waitForFunction(()=>document.querySelector('.topbar').classList.contains('is-scrolled'));
    assert.equal(await page.locator('.topbar').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(76, 57, 61)');
    assert.deepEqual(errors,[]);
    console.log('PASS: single translucent appearance, live transparency slider and persistence, overview, process search, folder inspection, health evidence, keyboard commands and mobile overflow. No renderer errors.');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
