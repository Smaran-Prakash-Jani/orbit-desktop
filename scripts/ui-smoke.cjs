const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser=await chromium.launch({headless:true,...(process.env.ORBIT_BROWSER_PATH?{executablePath:process.env.ORBIT_BROWSER_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  try {
    await page.goto(pathToFileURL(path.resolve(__dirname,'../ui/index.html')).href);
    await page.locator('#cpu-value').filter({hasText:'18.4'}).waitFor();
    await fs.mkdir(path.resolve(__dirname,'../test-results'),{recursive:true});
    await page.screenshot({path:'test-results/overview-silver.png',fullPage:true,animations:'disabled'});
    await page.getByRole('button',{name:'Open preferences',exact:true}).click();
    await page.getByRole('button',{name:'Obsidian',exact:true}).click();
    await page.getByRole('button',{name:'Overview',exact:true}).click();
    await page.screenshot({path:'test-results/overview-dark.png',fullPage:true,animations:'disabled'});
    await page.getByRole('button',{name:'Processes',exact:true}).click();
    await page.locator('#process-rows tr').first().waitFor();
    await page.getByLabel('Filter processes').fill('firefox');
    assert.equal(await page.locator('#process-rows tr').count(),1);
    assert.match(await page.locator('#process-rows').innerText(),/Firefox/);
    await page.getByLabel('Filter processes').fill('no-match-1234');
    assert.match(await page.locator('#process-rows').innerText(),/No processes match/);
    await page.getByRole('button',{name:'Storage',exact:true}).click();
    await page.getByRole('button',{name:'Inspect a folder',exact:true}).click();
    await page.getByText('Projects',{exact:true}).waitFor();
    assert.equal(await page.locator('.folder-row').count(),5);
    await page.getByRole('button',{name:'Health check',exact:true}).click();
    await page.locator('#view-health').getByRole('button',{name:'Run health check',exact:true}).click();
    await page.locator('.check-card').first().waitFor();
    assert.equal(await page.locator('.check-card').count(),6);
    await page.locator('.check-card summary').first().click();
    await page.screenshot({path:'test-results/health.png',fullPage:true});
    await page.keyboard.press('Control+k');
    await page.getByLabel('Search commands').fill('network');
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#view-network').isVisible(),true);
    assert.match(await page.locator('#network-download').innerText(),/428/);
    await page.getByRole('button',{name:'Open preferences',exact:true}).click();
    await page.getByLabel('Reduce motion').check();
    await page.getByLabel('Reduce transparency').check();
    await page.getByRole('button',{name:'Silver glass',exact:true}).click();
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
    assert.match(await page.locator('body').getAttribute('class'),/quiet-motion/);
    await page.getByRole('button',{name:'Open preferences',exact:true}).click();
    await page.getByLabel('Reduce transparency').uncheck();
    await page.getByRole('button',{name:'Overview',exact:true}).click();
    await page.screenshot({path:'test-results/overview-light.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'no horizontal overflow on mobile');
    await page.screenshot({path:'test-results/overview-mobile.png',fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('PASS: overview, process search, empty results, folder inspection, health evidence, keyboard commands, preference persistence, light theme and mobile overflow. No renderer errors.');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
